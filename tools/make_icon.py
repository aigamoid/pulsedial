# PulseDial launcher icon: LED-style pixel art (31 x 31 dots). Design B (white wave ring + blue play mark) is the one in use.
#   pip install numpy pillow
#   python3 tools/make_icon.py [A|B|C|D]   (no argument = only a comparison sheet of the 4 designs)
# Output: tools/icon_sheet.png (comparison), or main/assets/images/pulsedial_icon.c + tools/icon.png
import sys, math
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ICON = ROOT / "main/assets/images/pulsedial_icon.c"
OUT = ROOT / "tools"
I = 200
G = 31
C = I / G
SS = 16           # 1 粒を細かく描く倍率
S = G * SS
BLUE = (40, 120, 255)
CYAN = (70, 215, 255)
WHITE = (240, 248, 255)
NAVY = (22, 44, 96)


def to_cells(img):
    # 細かく描いた絵を、粒ごとの平均の色に (少し明るく: 縁の粒も光って見えるように)
    a = np.asarray(img, float).reshape(G, SS, G, SS, 3).mean(axis=(1, 3))
    return np.clip(a * 1.35, 0, 255)


def led(cells):
    out = np.zeros((I, I, 3))
    yy, xx = np.mgrid[0:I, 0:I]
    gi, gj = (yy // C).astype(int), (xx // C).astype(int)
    u = np.abs((xx + 0.5) / C - gj - 0.5); v = np.abs((yy + 0.5) / C - gi - 0.5)
    h, rad = 0.5 - 0.08, 0.26
    d = np.sqrt(np.maximum(u - (h - rad), 0) ** 2 + np.maximum(v - (h - rad), 0) ** 2) - rad
    a = np.clip(0.5 - d * C, 0, 1)[..., None]
    col = cells[gi, gj].astype(float)
    out = col * a + col * 0.12 * (1 - a)
    disc = ((xx - I / 2 + 0.5) ** 2 + (yy - I / 2 + 0.5) ** 2) <= (I / 2) ** 2
    out[~disc] = 0
    return np.clip(out, 0, 255).astype(np.uint8)


def wave_pts(c, R, amp, n=360, k1=5, k2=3, ph=0.4):
    pts = []
    for t in range(n + 1):
        ang = t / n * 2 * math.pi
        r = R + amp * math.sin(ang * k1 + ph) * math.cos(ang * k2)
        pts.append((c + r * math.cos(ang), c + r * math.sin(ang)))
    return pts


def design(kind):
    img = Image.new("RGB", (S, S), (0, 0, 0))
    d = ImageDraw.Draw(img)
    c = S / 2
    u = S / 31  # 1 粒
    if kind == "A":  # ストップウォッチ + イコライザー: 青い輪と上のりゅうず、中に 5 本のバー (白〜水色)
        R = 11.0 * u
        oy = 1.6 * u
        d.ellipse((c - R, c - R + oy, c + R, c + R + oy), outline=BLUE, width=int(1.8 * u))
        d.rectangle((c - 1.5 * u, c - R + oy - 2.4 * u, c + 1.5 * u, c - R + oy), fill=BLUE)   # りゅうず
        d.rectangle((c - 3.0 * u, c - R + oy - 3.6 * u, c + 3.0 * u, c - R + oy - 2.2 * u), fill=CYAN)
        base = 22 * u  # 粒の境目にそろえる (バーが 1 粒幅でくっきり、すき間も 2 粒)
        for k, hgt in enumerate((4, 7, 10, 6, 3)):
            x0 = (9 + 3 * k) * u
            col = WHITE if hgt > 6 else CYAN
            d.rectangle((x0, base - hgt * u, x0 + u - 1, base - 1), fill=col)
    elif kind == "B":  # 波形の輪 + ▷: アプリの静かな画面の白い波形を、そのままアイコンに
        d.line(wave_pts(c, 10.6 * u, 1.3 * u), fill=WHITE, width=int(1.1 * u), joint="curve")
        d.line(wave_pts(c, 12.6 * u, 0.6 * u, k1=7, ph=1.3), fill=NAVY, width=int(1.0 * u), joint="curve")
        tri = [(c - 3.2 * u, c - 4.6 * u), (c - 3.2 * u, c + 4.6 * u), (c + 4.8 * u, c)]
        d.polygon(tri, fill=BLUE)
    elif kind == "C":  # 拍の文字盤: 12 の目盛りがイコライザーのバー (長さがばらばら)。白い針が 1 本
        n = 12
        for k in range(n):
            ang = k / n * 2 * math.pi - math.pi / 2
            L = (2.2, 4.4, 3.0, 5.0, 2.6, 3.8, 4.8, 2.4, 4.0, 3.2, 5.0, 2.8)[k]
            r0, r1 = 8.6 * u, (8.6 + L) * u
            col = WHITE if k % 3 == 0 else (CYAN if L > 3.5 else BLUE)
            d.line((c + r0 * math.cos(ang), c + r0 * math.sin(ang), c + r1 * math.cos(ang), c + r1 * math.sin(ang)),
                   fill=col, width=int(1.6 * u))
        ang = -math.pi / 2 + math.pi / 3
        d.line((c, c, c + 6.4 * u * math.cos(ang), c + 6.4 * u * math.sin(ang)), fill=WHITE, width=int(1.3 * u))
        d.ellipse((c - 1.5 * u, c - 1.5 * u, c + 1.5 * u, c + 1.5 * u), fill=CYAN)
    else:  # D: 盤と進み具合: 紺のレコードの溝に、水色の弧 (再生バー) が 3/4 まで。真ん中は白い点
        for R in (5.0, 7.5, 10.0):
            d.ellipse((c - R * u, c - R * u, c + R * u, c + R * u), outline=NAVY, width=int(0.9 * u))
        R = 12.6 * u
        d.arc((c - R, c - R, c + R, c + R), start=-90, end=180, fill=CYAN, width=int(1.4 * u))
        d.arc((c - R, c - R, c + R, c + R), start=180, end=270, fill=NAVY, width=int(1.4 * u))
        a = math.radians(180)
        d.ellipse((c + R * math.cos(a) - 1.6 * u, c + R * math.sin(a) - 1.6 * u,
                   c + R * math.cos(a) + 1.6 * u, c + R * math.sin(a) + 1.6 * u), fill=WHITE)
        d.ellipse((c - 2.0 * u, c - 2.0 * u, c + 2.0 * u, c + 2.0 * u), fill=WHITE)
    return led(to_cells(img))


def write_c(icon):
    a = icon.astype(np.uint16)
    data = (((a[..., 0] >> 3) << 11) | ((a[..., 1] >> 2) << 5) | (a[..., 2] >> 3)).astype("<u2").tobytes()
    L = ["// Generated by tools/make_icon.py. Do not edit by hand", '#include "lvgl.h"', "",
         "const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t pulsedial_icon_map[] = {"]
    for k in range(0, len(data), 24):
        L.append("    " + ", ".join(f"0x{b:02x}" for b in data[k:k + 24]) + ",")
    L += ["};", "", "const lv_image_dsc_t pulsedial_icon = {", "    .header.cf    = LV_COLOR_FORMAT_RGB565,",
          "    .header.magic = LV_IMAGE_HEADER_MAGIC,", f"    .header.w     = {I},", f"    .header.h     = {I},",
          f"    .data_size    = {I * I} * 2,", "    .data         = pulsedial_icon_map,", "};"]
    ICON.write_text("\n".join(L) + "\n")


if len(sys.argv) > 1:
    icon = design(sys.argv[1].upper())
    write_c(icon)
    Image.fromarray(icon).save(OUT / "icon.png")
    print("icon ->", ICON)
else:
    kinds = "ABCD"
    sheet = Image.new("RGB", (len(kinds) * (I + 30) + 30, I + 70), (24, 24, 24))
    dr = ImageDraw.Draw(sheet)
    for k, kind in enumerate(kinds):
        sheet.paste(Image.fromarray(design(kind)), (30 + k * (I + 30), 50))
        dr.text((30 + k * (I + 30) + 95, 18), kind, fill=(240, 240, 240))
    big = sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST)
    out = OUT / "icon_sheet.png"
    big.save(out)
    print("sheet ->", out)
